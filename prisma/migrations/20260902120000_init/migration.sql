-- ============================================================================
-- Baseline migration — initializes the donation-platform schema.
-- ============================================================================
-- Created: 2026-09-02
-- Why this is "init" and not the project's first migration:
--   The repo previously had no `prisma/migrations/` directory tracked in git
--   (the files were deleted at some point between d3b8f82 and HEAD). The dev
--   DB has a `_prisma_migrations` row for `20260820200835_init`, but the
--   corresponding SQL is gone. This `init` migration:
--
--     1. Creates the `_prisma_migrations` table if it doesn't exist (prod
--        was bootstrapped via `prisma db push`, so it's missing).
--     2. Creates every enum, table, index, and FK from the current
--        `prisma/schema.prisma` using ONLY idempotent statements
--        (`CREATE ... IF NOT EXISTS`, `ADD COLUMN IF NOT EXISTS`,
--        `CREATE INDEX IF NOT EXISTS`, `DO $$ ... $$` for constraint
--        additions). This means the migration is safe to apply against
--        any DB state — a fully-empty DB, a partially-migrated DB
--        (like prod), or a freshly-reset DB. It will only add what's
--        missing and never error on pre-existing objects.
--
--   Future schema changes will produce normal non-idempotent migrations
--   via `pnpm prisma migrate dev --name <descriptive>`. The idempotency
--   here is purely a one-time concern to backfill prod into alignment
--   with the schema in source control.
--
-- DO NOT EDIT THIS FILE once it has been applied in production. Subsequent
-- schema changes go in new migrations. See CONTRIBUTING.md §Testing
-- Requirements and the schema-change checklist.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 0. Prisma migrations table (needed by `prisma migrate deploy` itself).
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
    "id"                    TEXT PRIMARY KEY,
    "checksum"              TEXT NOT NULL,
    "finished_at"           TIMESTAMP(3),
    "migration_name"        TEXT NOT NULL,
    "logs"                  TEXT,
    "rolled_back_at"        TIMESTAMP(3),
    "started_at"            TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "applied_steps_count"   INTEGER NOT NULL DEFAULT 0
);

-- ----------------------------------------------------------------------------
-- 1. Enums (create only if missing; add any new values to existing types).
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'UserRole') THEN
        CREATE TYPE "UserRole" AS ENUM ('USER', 'ADMIN');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'DonationStatus') THEN
        CREATE TYPE "DonationStatus" AS ENUM ('PENDING', 'SUCCESS', 'FAILED', 'CANCELLED');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'DonationPurpose') THEN
        CREATE TYPE "DonationPurpose" AS ENUM ('GENERAL_FUND', 'EDUCATION', 'MEDICAL', 'EMERGENCY');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'Language') THEN
        CREATE TYPE "Language" AS ENUM ('BN', 'EN');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'AuditSeverity') THEN
        CREATE TYPE "AuditSeverity" AS ENUM ('INFO', 'WARNING', 'CRITICAL');
    END IF;
END
$$;

-- ----------------------------------------------------------------------------
