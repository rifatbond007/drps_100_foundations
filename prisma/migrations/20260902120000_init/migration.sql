-- ----------------------------------------------------------------------------
-- 3. Columns. For tables that pre-exist in prod (because the schema has
-- been alive for a while), `CREATE TABLE IF NOT EXISTS` is a no-op and the
-- columns below are what actually backfills the drift. Every column uses
-- `ADD COLUMN IF NOT EXISTS` so re-running the migration is harmless.
-- ----------------------------------------------------------------------------
-- Account: no additive columns beyond the table definition.
-- Session: no additive columns.
-- VerificationToken: no additive columns.

-- User: ensure deletedAt + tokenVersion exist (added in 364adf9).
ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "deletedAt" TIMESTAMP(3);
ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "tokenVersion" INTEGER NOT NULL DEFAULT 0;

-- Donation: manual bKash fields (trxId/senderPhone/trxSubmittedAt + admin
-- review trail — added in 364adf9). These are the columns the failing
-- /api/donations/history route selects but prod doesn't have.
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "trxId" TEXT;
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "senderPhone" TEXT;
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "trxSubmittedAt" TIMESTAMP(3);
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "reviewedById" TEXT;
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "reviewedAt" TIMESTAMP(3);
ALTER TABLE "Donation" ADD COLUMN IF NOT EXISTS "adminNote" TEXT;
-- Also make sure the `failureReason` and `paymentMethod` defaults are right.
-- (No-op if already correct; `SET DEFAULT` is idempotent.)
ALTER TABLE "Donation" ALTER COLUMN "paymentMethod" SET DEFAULT 'manual_bkash';

-- AuditLog: severity + correlationId (used by fail() persistError).
ALTER TABLE "AuditLog" ADD COLUMN IF NOT EXISTS "severity" "AuditSeverity" NOT NULL DEFAULT 'INFO';
ALTER TABLE "AuditLog" ADD COLUMN IF NOT EXISTS "correlationId" TEXT;

